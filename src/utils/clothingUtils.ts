/**
 * Determines whether a given line-item description or query is for
 * clothes / kapda / kids wear.
 * If false (e.g. Water Bill, Bijli bill, repair, tea, rent, service):
 * the size section MUST be completely hidden!
 */
export function isClothingOrKidsItem(description?: string): boolean {
  if (!description) return false;
  const d = description.toLowerCase().trim();

  // Explicit non-clothing check for faster rejection
  if (
    d.includes('water') ||
    d.includes('pani') ||
    d.includes('bijali') ||
    d.includes('bijli') ||
    d.includes('light bill') ||
    d.includes('electric') ||
    d.includes('rent') ||
    d.includes('kiraya') ||
    d.includes('tea') ||
    d.includes('chai') ||
    d.includes('nashta') ||
    d.includes('recharge') ||
    d.includes('mobile') ||
    d.includes('transport') ||
    d.includes('bhada') ||
    d.includes('petrol') ||
    d.includes('courier') ||
    d.includes('repair') ||
    d.includes('service')
  ) {
    return false;
  }

  return CLOTHING_KEYWORDS.some((kw) => d.includes(kw));
}

/**
 * Extracts year or age size from text if specified (e.g. "3-4 yrs", "2 saal", "5 years", "1-2y")
 */
export function extractYearsOrSize(text: string): string {
  if (!text) return '';
  const yrsMatch = text.match(
    /(\d+(?:-\d+)?)\s*(?:saal|year|years|yrs|yr|y|m|month|months)\b/i
  );
  if (yrsMatch) {
    const num = yrsMatch[1];
    const unit = text.toLowerCase().includes('m') && !text.toLowerCase().includes('y') ? 'M' : 'Yrs';
    return `${num} ${unit}`;
  }
  return '';
}

/**
 * Sanitizes invoice notes to strictly ensure NOTHING related to AI
 * (e.g. "verified via AI", "generated by AI", "AI note") ever appears on an invoice.
 */
export function sanitizeInvoiceNote(note?: string): string {
  if (!note) return '';
  // Check for AI keywords
  if (/\b(?:ai|bot|artificial\s*intelligence|verified\s*via\s*ai|generated\s*by\s*ai)\b/i.test(note)) {
    return '';
  }
  return note.trim();
}
